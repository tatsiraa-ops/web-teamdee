const setP = (cards, map) => { for (const c of cards || []) if (map?.[c.h]) c.p = [map[c.h]] }

export function fixProductCopy(out) {
  for (const [id, p] of Object.entries(out)) {
    if (id[0] === '_') continue
    setP(p.production.cards, PRODUCTION[id])
    setP(p.detail.cards, DETAIL[id])
    setP(p.options.cards, OPTION[id])
    for (const s of p.order.steps || []) if (s.h === 'ตรวจแบบและรายการ' && STEP2[id]) s.p = STEP2[id]
    p.fabric.intro = p.fabric.intro.map((t) => (t.startsWith('เทียบวัสดุ') ? FABRIC_INTRO : t))
    if (p.detail.table?.head?.[1] === 'ข้อมูลประกอบการตัดสินใจ') p.detail.table.head[1] = 'รายละเอียด'
    p.size.p = (p.size.p || []).map((t) => t.replace(' พร้อมภาพผู้สวมที่ระบุส่วนสูงและไซซ์จริง', ''))
    p.faq.items = applyFaq(p.faq.items)
  }
}
